def get_glaucoma_notice() -> str:
    return (
        "El glaucoma no puede detectarse de forma confiable mediante una "
        "fotografía externa convencional. Requiere evaluación oftalmológica, "
        "presión intraocular y fondo de ojo. El sistema solo puede advertir "
        "signos externos compatibles en casos agudos, como ojo muy rojo, "
        "pupila fija o córnea opaca."
    )
